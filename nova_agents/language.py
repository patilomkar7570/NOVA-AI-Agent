"""Shared NOVA conversation-language policy and lightweight language detection."""
from __future__ import annotations

import re
import unicodedata

SUPPORTED_CONVERSATION_LANGUAGES = {
    "auto": "Automatic",
    "en": "English",
    "de": "German",
    "fr": "French",
    "es": "Spanish",
    "ja": "Japanese",
    "hi": "Hindi",
}

WHISPER_LANGUAGE_CODES = frozenset({"en", "de", "fr", "es", "ja", "hi"})


def normalize_language(value: object, default: str = "en") -> str:
    """Normalise a selected language to NOVA's small supported set."""
    raw = str(value or "").strip().lower().replace("_", "-")
    if raw in {"automatic", "detect", "autodetect", "auto-detect"}:
        return "auto"
    code = raw.split("-", 1)[0]
    if code in SUPPORTED_CONVERSATION_LANGUAGES:
        return code
    safe_default = str(default or "en").lower()
    return safe_default if safe_default in SUPPORTED_CONVERSATION_LANGUAGES else "en"


def detect_language_from_text(text: object, fallback: str | None = None) -> str | None:
    """A small deterministic hint detector for NOVA's six supported languages.

    Whisper remains the authority for incoming audio. This helper is used only
    to choose a compatible speech voice for text already generated by Qwen and
    to localise short deterministic agent acknowledgements.
    """
    value = str(text or "").strip()
    if not value:
        return fallback

    # Script-based signals are strong and do not need a model call.
    if re.search(r"[\u0900-\u097F]", value):
        return "hi"
    if re.search(r"[\u3040-\u30FF]", value):
        return "ja"

    words = re.findall(r"[\wÀ-ÿ']+", value.casefold())
    if not words:
        return fallback

    markers = {
        "fr": {"le", "la", "les", "des", "et", "est", "pas", "avec", "pour", "je", "vous", "nous", "une", "dans", "que", "qui", "sur", "mais", "bonjour", "merci", "oui", "non", "voudrais", "parler", "comment", "ça"},
        "es": {"el", "los", "las", "y", "es", "no", "con", "para", "yo", "tú", "una", "que", "por", "del", "como", "pero", "está", "hola", "gracias", "buenos", "días", "quiero", "hablar", "cómo"},
        "de": {"der", "die", "das", "und", "ist", "nicht", "mit", "für", "ich", "ein", "eine", "wir", "sie", "auf", "von", "zu", "auch", "aber", "hallo", "guten", "morgen", "danke", "bitte", "sprechen"},
        "en": {"the", "and", "is", "not", "with", "for", "you", "we", "a", "an", "of", "to", "in", "that", "this", "are", "but", "hello", "thanks", "please"},
    }
    scores = {code: sum(1 for token in words if token in terms) for code, terms in markers.items()}
    accents = {
        "de": sum(value.count(char) for char in "äöüß"),
        "fr": sum(value.count(char) for char in "àâçéèêëîïôùûüÿœ"),
        "es": sum(value.count(char) for char in "áéíóúñ¿¡"),
    }
    for code, score in accents.items():
        scores[code] += score * 2

    best = max(scores, key=scores.get)
    # Require a useful margin; a short Latin-script word is not enough evidence.
    ordered = sorted(scores.values(), reverse=True)
    if scores[best] == 0 or (len(words) < 4 and scores[best] < 2):
        return fallback
    if len(ordered) > 1 and ordered[0] - ordered[1] < 1:
        return fallback
    return best


# Voicebox engine names and language coverage used for per-request routing.
# Chatterbox Multilingual is selected for Hindi cloned profiles; Kokoro can
# also speak Hindi, but its Hindi voices are fixed presets rather than clones.
VOICEBOX_TTS_ENGINE_LANGUAGES = {
    "qwen": frozenset({"en", "de", "fr", "es", "ja"}),
    "qwen_custom_voice": frozenset({"en", "ja"}),
    "chatterbox": frozenset({"en", "de", "fr", "es", "ja", "hi"}),
    "chatterbox_turbo": frozenset({"en"}),
    "kokoro": frozenset({"en", "fr", "es", "ja", "hi"}),
    "luxtts": frozenset({"en"}),
    "tada": frozenset({"en"}),
}

def voicebox_engine_supports_language(engine: object, language: object) -> bool:
    engine_name = str(engine or "").strip().lower().replace("-", "_")
    code = normalize_language(language, default="auto")
    if code == "auto":
        return False
    supported = VOICEBOX_TTS_ENGINE_LANGUAGES.get(engine_name)
    if supported is None and "chatterbox" in engine_name and "turbo" not in engine_name:
        supported = VOICEBOX_TTS_ENGINE_LANGUAGES["chatterbox"]
    return bool(supported and code in supported)

def preferred_voicebox_engine(language: object) -> str:
    code = normalize_language(language, default="en")
    return "chatterbox" if code == "hi" else "qwen"

def language_instruction(language: object) -> str:
    """Return the shared instruction appended to every user-facing Qwen path."""
    code = normalize_language(language, default="auto")
    if code == "auto":
        return (
            "LANGUAGE POLICY: Reply in the same language as the user's latest message. "
            "Follow a clear language switch by the user and keep using that language. "
            "Do not translate the user's request unless asked. Preserve names, URLs, "
            "technical identifiers and quoted source text where appropriate. Keep any "
            "required JSON keys, tool syntax, code, filenames and machine-readable fields unchanged."
        )
    name = SUPPORTED_CONVERSATION_LANGUAGES[code]
    script_note = " Use Devanagari script." if code == "hi" else ""
    return (
        f"LANGUAGE POLICY: Write all user-facing natural-language replies in {name} only."
        f"{script_note} Do not switch to English or another language unless the user explicitly "
        "asks you to. Do not translate the user's request unless asked. Preserve proper names, "
        "URLs, technical identifiers, commands and quoted source text where appropriate. Keep "
        "required JSON keys, tool syntax, code, filenames and machine-readable fields unchanged."
    )
